    -- 그 최신 행 자체가 TRDG02 소속이며 복구 가능한 0003/0004/0005일 때만 확정한다.
    DROP TEMPORARY TABLE IF EXISTS TMP_F_OPS_005_006_PREV_STATUS;
    CREATE TEMPORARY TABLE TMP_F_OPS_005_006_PREV_STATUS AS
    SELECT TRD_DSP_SN, TRD_STS_HST_STATUS_CD
    FROM (
        SELECT d.TRD_DSP_SN,
               h.TRD_STS_HST_STATUS_CD,
               ROW_NUMBER() OVER (
                   PARTITION BY d.TRD_DSP_SN
                   ORDER BY h.TRD_STS_HST_REG_DT DESC, h.TRD_STS_HST_SN DESC
               ) AS rn
        FROM TRADE_DISPUTE d
        JOIN TRADE_STATUS_HIST h
          ON h.TRD_SN = d.TRD_SN
         AND h.TRD_STS_HST_REG_DT < d.TRD_DSP_REG_DT
        WHERE d.TRD_DSP_PREV_TRD_STATUS_CD IS NULL
    ) ranked
    JOIN CMM_CODE status_code
      ON status_code.CMM_CD = ranked.TRD_STS_HST_STATUS_CD
    JOIN CMM_CODE status_group
      ON status_group.CMM_SN = status_code.CMM_PARENT_SN
     AND status_group.CMM_CD = 'TRDG02'
    WHERE ranked.rn = 1
      AND ranked.TRD_STS_HST_STATUS_CD IN ('TRDC0003', 'TRDC0004', 'TRDC0005');

    UPDATE TRADE_DISPUTE d
    JOIN TMP_F_OPS_005_006_PREV_STATUS p ON p.TRD_DSP_SN = d.TRD_DSP_SN
    SET d.TRD_DSP_PREV_TRD_STATUS_CD = p.TRD_STS_HST_STATUS_CD
    WHERE d.TRD_DSP_PREV_TRD_STATUS_CD IS NULL;

    SET v_backfilled_count = ROW_COUNT();
    DROP TEMPORARY TABLE TMP_F_OPS_005_006_PREV_STATUS;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.STATISTICS
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND SEQ_IN_INDEX = 1 AND COLUMN_NAME = 'TRD_DSP_RSLT_CD'
    ) THEN
        ALTER TABLE TRADE_DISPUTE
            ADD KEY IDX_TRADE_DISPUTE_RESULT (TRD_DSP_RSLT_CD);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.STATISTICS
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND SEQ_IN_INDEX = 1 AND COLUMN_NAME = 'TRD_DSP_PROC_USR_SN'
    ) THEN
        ALTER TABLE TRADE_DISPUTE
            ADD KEY IDX_TRADE_DISPUTE_PROC_USR (TRD_DSP_PROC_USR_SN);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.STATISTICS
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND SEQ_IN_INDEX = 1 AND COLUMN_NAME = 'TRD_DSP_PREV_TRD_STATUS_CD'
    ) THEN
        ALTER TABLE TRADE_DISPUTE
            ADD KEY IDX_TRADE_DISPUTE_PREV_STATUS (TRD_DSP_PREV_TRD_STATUS_CD);
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND COLUMN_NAME = 'TRD_DSP_RSLT_CD' AND REFERENCED_TABLE_NAME IS NOT NULL
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND COLUMN_NAME = 'TRD_DSP_RSLT_CD'
          AND REFERENCED_TABLE_SCHEMA = DATABASE()
          AND REFERENCED_TABLE_NAME = 'CMM_CODE' AND REFERENCED_COLUMN_NAME = 'CMM_CD'
    ) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'F-OPS-005/006 중단: TRD_DSP_RSLT_CD FK 대상이 다릅니다.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND COLUMN_NAME = 'TRD_DSP_RSLT_CD' AND REFERENCED_TABLE_NAME IS NOT NULL
    ) THEN
        ALTER TABLE TRADE_DISPUTE
            ADD CONSTRAINT FK_TRADE_DISPUTE_RESULT_CODE
            FOREIGN KEY (TRD_DSP_RSLT_CD) REFERENCES CMM_CODE (CMM_CD)
            ON DELETE RESTRICT ON UPDATE RESTRICT;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND COLUMN_NAME = 'TRD_DSP_PROC_USR_SN' AND REFERENCED_TABLE_NAME IS NOT NULL
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND COLUMN_NAME = 'TRD_DSP_PROC_USR_SN'
          AND REFERENCED_TABLE_SCHEMA = DATABASE()
          AND REFERENCED_TABLE_NAME = 'USERS' AND REFERENCED_COLUMN_NAME = 'USR_SN'
    ) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'F-OPS-005/006 중단: TRD_DSP_PROC_USR_SN FK 대상이 다릅니다.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND COLUMN_NAME = 'TRD_DSP_PROC_USR_SN' AND REFERENCED_TABLE_NAME IS NOT NULL
    ) THEN
        ALTER TABLE TRADE_DISPUTE
            ADD CONSTRAINT FK_TRADE_DISPUTE_PROCESSOR
            FOREIGN KEY (TRD_DSP_PROC_USR_SN) REFERENCES USERS (USR_SN)
            ON DELETE RESTRICT ON UPDATE RESTRICT;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND COLUMN_NAME = 'TRD_DSP_PREV_TRD_STATUS_CD' AND REFERENCED_TABLE_NAME IS NOT NULL
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND COLUMN_NAME = 'TRD_DSP_PREV_TRD_STATUS_CD'
          AND REFERENCED_TABLE_SCHEMA = DATABASE()
          AND REFERENCED_TABLE_NAME = 'CMM_CODE' AND REFERENCED_COLUMN_NAME = 'CMM_CD'
