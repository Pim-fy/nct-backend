        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'F-OPS-005/006 중단: TRD_DSP_PREV_TRD_STATUS_CD FK 대상이 다릅니다.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.KEY_COLUMN_USAGE
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TRADE_DISPUTE'
          AND COLUMN_NAME = 'TRD_DSP_PREV_TRD_STATUS_CD' AND REFERENCED_TABLE_NAME IS NOT NULL
    ) THEN
        ALTER TABLE TRADE_DISPUTE
            ADD CONSTRAINT FK_TRADE_DISPUTE_PREV_STATUS_CODE
            FOREIGN KEY (TRD_DSP_PREV_TRD_STATUS_CD) REFERENCES CMM_CODE (CMM_CD)
            ON DELETE RESTRICT ON UPDATE RESTRICT;
    END IF;

    SELECT v_backfilled_count AS backfilled_previous_trade_status_count;
END $$

